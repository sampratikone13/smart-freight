import React from 'react';
import { Clock, AlertTriangle, CheckCircle, Info, Package, MapPin, Tag, Calendar } from 'lucide-react';

export default function PredictionResult({ result, submittedData }) {
  if (!result) return null;

  const isDelayed = result.is_delayed_risk;
  const days = result.predicted_shipping_days;
  const scheduled = result.scheduled_shipping_days;
  const diff = result.difference_days;

  return (
    <div className="bg-white rounded-2xl border border-slate-200/90 overflow-hidden shadow-sm transition-all animate-fadeIn">
      {/* Top Status Header */}
      <div className={`px-6 py-4 flex items-center justify-between border-b ${
        isDelayed 
          ? 'bg-amber-500/10 border-amber-500/20 text-amber-900' 
          : 'bg-emerald-500/10 border-emerald-500/20 text-emerald-900'
      }`}>
        <div className="flex items-center gap-2.5">
          {isDelayed ? (
            <div className="h-7 w-7 rounded-full bg-amber-100 flex items-center justify-center text-amber-700">
              <AlertTriangle className="h-4 w-4" />
            </div>
          ) : (
            <div className="h-7 w-7 rounded-full bg-emerald-100 flex items-center justify-center text-emerald-700">
              <CheckCircle className="h-4 w-4" />
            </div>
          )}
          <div>
            <p className="font-bold text-sm leading-none">
              {isDelayed ? 'Potential Shipping Delay Risk' : 'Shipment On Schedule'}
            </p>
            <p className="text-2xs text-slate-500 mt-0.5">
              {isDelayed 
                ? 'Predicted transit duration exceeds the promised SLA delivery window.' 
                : 'Predicted transit duration meets or outperforms the carrier SLA.'}
            </p>
          </div>
        </div>

        <span className="text-2xs font-bold uppercase tracking-wider px-3 py-1 rounded-full bg-white border border-slate-200 shadow-2xs text-slate-700">
          {result.speed_category || 'Standard Delivery'}
        </span>
      </div>

      <div className="p-6 sm:p-7 space-y-6">
        {/* Main Result Display */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-6 pb-6 border-b border-slate-100">
          <div>
            <p className="text-xs font-bold text-slate-400 uppercase tracking-wider">Estimated Shipping Duration</p>
            <div className="flex items-baseline gap-2 mt-1">
              <span className="text-5xl sm:text-6xl font-black text-slate-900 tracking-tight">{days}</span>
              <span className="text-2xl font-bold text-slate-500">Days</span>
            </div>
            <p className="text-xs text-slate-500 mt-1">
              Whole-day duration generated by Random Forest Regression
            </p>
          </div>

          <div className="bg-slate-50 rounded-xl p-4 sm:text-right border border-slate-200/80 min-w-[200px]">
            <p className="text-xs font-semibold text-slate-400 uppercase tracking-wider">Scheduled SLA Promise</p>
            <p className="text-2xl font-extrabold text-slate-800 mt-0.5">{scheduled} Days</p>
            <div className="mt-1 text-xs font-semibold">
              {diff > 0 ? (
                <span className="text-amber-600">+{diff} {diff === 1 ? 'day' : 'days'} longer than SLA</span>
              ) : diff < 0 ? (
                <span className="text-emerald-600">{Math.abs(diff)} {Math.abs(diff) === 1 ? 'day' : 'days'} earlier than SLA</span>
              ) : (
                <span className="text-blue-600">Exact match with scheduled SLA</span>
              )}
            </div>
          </div>
        </div>

        {/* Speed Category Explanation Box */}
        <div className="flex items-start gap-3 bg-blue-50/60 rounded-xl p-4 border border-blue-100">
          <Info className="h-5 w-5 text-blue-600 shrink-0 mt-0.5" />
          <div>
            <p className="text-xs font-bold text-blue-900 uppercase tracking-wide">{result.speed_category}</p>
            <p className="text-xs text-blue-800/90 mt-0.5 leading-relaxed">{result.description}</p>
          </div>
        </div>

        {/* Summary of Submitted Order */}
        {submittedData && (
          <div className="bg-slate-50/70 rounded-xl border border-slate-200/80 p-4">
            <h4 className="text-2xs font-bold uppercase tracking-wider text-slate-400 mb-3 flex items-center gap-1.5">
              <Package className="h-3.5 w-3.5 text-slate-500" />
              Submitted Order Summary
            </h4>
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
              <div>
                <span className="text-slate-400 text-2xs block">Shipping Mode</span>
                <span className="font-semibold text-slate-800">{submittedData['Shipping Mode'] || 'Standard'}</span>
              </div>
              <div>
                <span className="text-slate-400 text-2xs block">Destination</span>
                <span className="font-semibold text-slate-800">{submittedData['Order Country'] || submittedData['Market']}</span>
              </div>
              <div>
                <span className="text-slate-400 text-2xs block">Category</span>
                <span className="font-semibold text-slate-800">{submittedData['Category Name'] || 'General'}</span>
              </div>
              <div>
                <span className="text-slate-400 text-2xs block">Sales / Items</span>
                <span className="font-semibold text-slate-800">${submittedData['Sales']} ({submittedData['Order Item Quantity']}x)</span>
              </div>
            </div>
          </div>
        )}

        {/* Operational Disclaimer */}
        <p className="text-2xs text-slate-400 text-center leading-relaxed">
          {result.disclaimer || 'This is an estimated shipping duration, not a guaranteed delivery date.'}
        </p>
      </div>
    </div>
  );
}
